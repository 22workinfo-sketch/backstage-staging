import { Bot, Keyboard, InlineKeyboard } from "grammy";
import dotenv from "dotenv";
import {
  handleTelegramStart,
  handleTelegramContact,
  handleTelegramText,
} from "../lib/bot-service";
import {
  scheduleMessageDeletion,
  processDueDeletions,
} from "../lib/deletion-service";
import {
  getBotChannels,
  checkUserChannelMemberships,
} from "../lib/channel-service";

dotenv.config();

const token = process.env.TELEGRAM_BOT_TOKEN;
const botId =
  process.env.BOT_DEFAULT_ID || "00000000-0000-0000-0000-000000000001";

const isPlaceholderToken =
  !token ||
  token.trim() === "" ||
  token.includes("placeholder") ||
  token.includes("your_test_bot_token");

