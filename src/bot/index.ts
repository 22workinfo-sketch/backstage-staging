import { Bot, Keyboard, InlineKeyboard } from "grammy";
import dotenv from "dotenv";
import {
  handleTelegramStart,
  handleTelegramContact,
  handleTelegramText,
} from "../lib/bot-service";
import {
  scheduleMessageDeletion,
  processDueDeletions,
} from "../lib/deletion-service";

dotenv.config();

const token = process.env.TELEGRAM_BOT_TOKEN;
const botId =
  process.env.BOT_DEFAULT_ID || "00000000-0000-0000-0000-000000000001";

const isPlaceholderToken =
  !token ||
  token.trim() === "" ||
  token.includes("placeholder") ||
  token.includes("your_test_bot_token");

if (isPlaceholderToken) {
  console.log("=============================================================");
  console.log(" [BackStage Bot Service - Mock / Standby Mode]");
  console.log("=============================================================");
  console.log("TELEGRAM_BOT_TOKEN is not configured with a live BotFather token.");
  console.log("The bot runner is in STANDBY mode.");
  console.log("");
  console.log("To connect your live Telegram test bot:");
  console.log("  1. Talk to @BotFather on Telegram and create a new bot.");
  console.log("  2. Copy the token generated by BotFather.");
  console.log("  3. Place it in your local .env file:");
  console.log('     TELEGRAM_BOT_TOKEN="123456789:ABCdefGHIjklMNOpqrSTUvwxYZ"');
  console.log("  4. Start the bot runner with: npm.cmd run bot");
  console.log("");
  console.log("All admin web panel features and automated tests continue to");
  console.log("work without needing a live Telegram connection.");
  console.log("=============================================================");
  process.exit(0);
}

console.log("[Bot Runner] Initializing Telegram bot long polling...");

// Initialize grammY bot
const bot = new Bot(token!);

// Handle /start command
bot.command("start", async (ctx) => {
  try {
    const from = ctx.from;
    if (!from) return;

    // Process user profile and get dynamic greeting from database
    const result = await handleTelegramStart({
      botId,
      telegramId: from.id,
      firstName: from.first_name,
      lastName: from.last_name,
      username: from.username,
      languageCode: from.language_code,
    });

    // Dynamically build reply keyboard from PostgreSQL menu buttons
    const replyKeyboard = new Keyboard();
    const configuredButtons = result.buttons || [];

    if (configuredButtons.length > 0) {
      for (const btn of configuredButtons) {
        if (btn.actionType === "REQUEST_CONTACT") {
          replyKeyboard.requestContact(btn.label).row();
        } else {
          replyKeyboard.text(btn.label).row();
        }
      }
    } else {
      // Fallback default
      replyKeyboard.text("ℹ️ Help / Info").row();
    }

    replyKeyboard.resized();

    const optionalNotice =
      "\n\n━━━━━━━━━━━━━━━━━━━━\n" +
      "ℹ️ Note: Sharing your phone number is completely optional. If you choose to tap '📱 Share Phone Number', your number will be made available to authorized backstage staff for customer support and contact purposes. You can freely use /start and the menu without sharing.";

    await ctx.reply(result.welcomeMessage + optionalNotice, {
      reply_markup: replyKeyboard,
    });

    console.log(
      `[Bot Runner] Handled /start for user @${from.username ?? "no_username"} (${from.id})`
    );
  } catch (error) {
    console.error("[Bot Runner Error] Failed to handle /start:", error instanceof Error ? error.message : "Unknown error");
    await ctx.reply("Sorry, a temporary error occurred while connecting to Backstage. Please try again later.");
  }
});

// Handle contact sharing (captures and securely verifies telegram_ph_no)
bot.on(":contact", async (ctx) => {
  try {
    const contact = ctx.message?.contact;
    const from = ctx.from;
    if (!contact || !from) return;

    const result = await handleTelegramContact({
      botId,
      senderTelegramId: from.id,
      contactUserId: contact.user_id,
      phoneNumber: contact.phone_number,
    });

    if (result.success) {
      console.log(`[Bot Runner] Verified and recorded contact for Telegram user ${from.id}`);
      await ctx.reply("✅ Thank you! Your phone number has been verified and securely recorded for support purposes in Backstage.");
    } else {
      console.warn(`[Bot Runner] Contact rejected for Telegram user ${from.id}. Reason: ${result.reason}`);
      await ctx.reply(
        "⚠️ We could not verify this phone number.\n\n" +
          "To protect your account, we only accept your own personal contact. " +
          "Please tap the '📱 Share Phone Number' button below rather than forwarding a contact card."
      );
    }
  } catch (error) {
    console.error("[Bot Runner Error] Failed to process contact:", error instanceof Error ? error.message : "Unknown error");
    await ctx.reply("Could not record phone number due to a temporary error. Please try again.");
  }
});

// Handle dynamic reply keyboard button presses (SEND_TEXT)
bot.on("message:text", async (ctx, next) => {
  const text = ctx.message?.text;
  if (!text || text.startsWith("/")) {
    return next(); // Let commands like /start pass through
  }

  try {
    const result = await handleTelegramText(botId, text);
    if (result.handled && result.replyText) {
      // 1. Send the configured reply to Telegram
      const sent = await ctx.reply(result.replyText);
      console.log(
        `[Bot Runner] Handled menu action for button "${text}" (user ${ctx.from?.id})`
      );

      // 2. If auto-delete is enabled, schedule persistent deletion in PostgreSQL
      // Notice: Countdown timer starts strictly AFTER Telegram confirms message was sent!
      if (result.button?.autoDeleteReply && result.button?.deleteAfterSeconds) {
        try {
          await scheduleMessageDeletion({
            botId,
            chatId: String(sent.chat.id),
            messageId: sent.message_id,
            deleteAfterSeconds: result.button.deleteAfterSeconds,
          });
          console.log(
            `[AutoDelete] Scheduled deletion for message ID ${sent.message_id} in chat ${sent.chat.id} after ${result.button.deleteAfterSeconds}s`
          );
        } catch (schedErr) {
          console.error(
            "[AutoDelete Error] Failed to schedule message deletion:",
            schedErr instanceof Error ? schedErr.message : schedErr
          );
        }
      }

      return;
    }
  } catch (error) {
    console.error(
      "[Bot Runner Error] Error evaluating menu button text:",
      error instanceof Error ? error.message : "Unknown error"
    );
  }

  // Gracefully pass unhandled text (e.g. disabled/removed buttons or standard chat)
  return next();
});

// Periodic sweeper: sweeps and executes due deletions from PostgreSQL
let sweeperBusy = false;
const deletionInterval = setInterval(async () => {
  if (sweeperBusy) return;
  sweeperBusy = true;
  try {
    const sweepRes = await processDueDeletions({
      botId,
      deleteMessageFn: async (chatId, messageId) => {
        await bot.api.deleteMessage(chatId, messageId);
      },
    });
    if (sweepRes.completedCount > 0 || sweepRes.failedCount > 0) {
      console.log(
        `[AutoDelete Sweeper] Batch complete: ${sweepRes.completedCount} deleted, ${sweepRes.failedCount} failed/permanent`
      );
    }
  } catch (err) {
    console.error(
      "[AutoDelete Sweeper Error]",
      err instanceof Error ? err.message : err
    );
  } finally {
    sweeperBusy = false;
  }
}, 3000);

// Sanitize errors (never leak bot token in error traces)
bot.catch((err) => {
  const sanitizedMessage = String(err.message || "").replace(
    /\d+:[A-Za-z0-9_-]{35}/g,
    "[REDACTED_BOT_TOKEN]"
  );
  console.error("[Bot Runner Global Error]", sanitizedMessage);
});

// Start long polling
bot.start({
  onStart: (botInfo) => {
    console.log(`[Bot Runner] Long polling active for @${botInfo.username} (ID: ${botInfo.id})`);
    console.log("[Bot Runner] Ready to receive Telegram messages. Press Ctrl+C to stop.");
  },
});

// Graceful shutdown
const stopBot = async () => {
  console.log("\n[Bot Runner] Stopping long polling and sweeper gracefully...");
  clearInterval(deletionInterval);
  await bot.stop();
  process.exit(0);
};

process.once("SIGINT", stopBot);
process.once("SIGTERM", stopBot);
